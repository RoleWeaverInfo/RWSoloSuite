// Run the same graph adapter used by the browser against a real authoring draft.
const fs=require('fs'),vm=require('vm'),assert=require('assert');
const ctx={window:{}};vm.createContext(ctx);
for(const name of ['mission-model','mission-graph'])vm.runInContext(fs.readFileSync('web/'+name+'.js','utf8'),ctx);
const M=ctx.window.MissionModel,G=ctx.window.MissionGraph;
const original=JSON.parse(fs.readFileSync(0,'utf8')),p=M.copy(original);
assert.equal(M.issues(p).length,0);
const q=p.quests[1],decision=q.steps.find(s=>s.kind==='choice'),first=decision.choices[0].next,second=decision.choices[1].next;
const graph=M.graph(p,q.id);
assert(graph.edges.some(e=>e.from==='@start'&&e.to===q.steps[0].id));
assert(graph.edges.some(e=>e.from===decision.id&&e.to===first&&e.choice===0));
assert(graph.edges.some(e=>e.from===decision.id&&e.to===second&&e.choice===1));
assert(!graph.edges.some(e=>e.from===first&&e.to===second),'Array order must not become a quest connection');
const overview=M.graph(p);
assert(overview.edges.some(e=>e.from===q.requires[0]&&e.to===q.id));
const optional=M.copy(p);optional.quests[1].optional=true;
assert(!M.graph(optional).edges.some(e=>e.from===q.id&&e.to==='@ending'));
assert(M.graph(p).edges.some(e=>e.from===q.id&&e.to==='@ending'));
// Editing branches changes the executable data, not a separate display graph.
M.connect(q,decision.id,second,0);M.connect(q,decision.id,first,1);
decision.choices[0].label='Choose the sealed path';decision.choices[1].label='Choose the restored path';
assert.equal(q.steps.find(s=>s.id===decision.id).choices[0].next,second);
const terminal=q.steps.find(s=>s.id===first),before=JSON.stringify(q);
assert.throws(()=>M.connect(q,terminal.id,q.steps[0].id),/loop/);
assert.throws(()=>M.connect(q,terminal.id,'absent'),/Choose an objective/);
assert.equal(JSON.stringify(q),before,'Rejected connections must preserve the draft');
const inserted=M.addStep(p,q,terminal);inserted.name='Tell Ilyra the outcome';inserted.target='ilyra';
assert.equal(terminal.next,inserted.id);assert.equal(inserted.next,'');
assert.equal(M.issues(p).length,0);
const removal=M.copy(q);M.removeStep(removal,inserted.id);
assert.equal(removal.steps.find(s=>s.id===first).next,'');
assert(!removal.steps.some(s=>s.id===inserted.id));
const entry=M.copy(q),next=entry.steps[0].next;M.removeStep(entry,entry.steps[0].id);
assert.equal(entry.steps[0].id,next);
assert(M.references(p,p.quests[0].id).some(s=>s.includes(q.name)));
assert.deepEqual(Array.from(M.targets(p,'defeat'),t=>t.id),p.encounters.filter(e=>['combat','ambush'].includes(e.kind)).map(e=>e.id));
assert.equal(M.targets(p,'visit').length,p.areas.reduce((n,a)=>n+a.rooms.length,0));
const broken=M.copy(p);broken.quests[1].steps[0].next='missing';
assert(M.issues(broken).some(e=>e.message.includes('Missing next')));
assert(M.issues(broken).some(e=>e.message.includes('cannot be reached')));
assert(M.graph(broken,q.id).nodes.some(n=>n.id==='missing'&&n.invalid));
const cyclic=M.copy(p);cyclic.quests[0].requires=[q.id];
assert(M.issues(cyclic).some(e=>e.message.includes('prerequisites contain a loop')));
assert(G.layout(M.graph(cyclic)).nodes.every(n=>Number.isFinite(n.x)));
const empty=M.copy(p);empty.quests=[];const added=M.newQuest(empty);
assert(M.issues(empty).some(e=>e.message.includes('at least one objective')));
M.addStep(empty,added,null,'choice');assert.equal(added.steps[0].choices.length,2);
assert.equal(M.issues(empty).length,0);
const untrusted=G.layout({nodes:[{id:'one',label:'<img src=x onerror=alert(1)>',lines:['"bad"'],badge:'<script>'},{id:'two',label:'End'}],edges:[{from:'one',to:'two',label:'<svg onload=alert(1)>'}]});
const markup=G.drawing(untrusted,'one');assert(!markup.includes('<img'));assert(!markup.includes('<script>'));assert(markup.includes('&lt;svg'));
assert(!Object.hasOwn(M.snapshot(p),'areas'));assert(!Object.hasOwn(M.snapshot(p),'npcs'));
q.gold=321;q.xp=654;q.completion='The edited mission is complete.';p.ending='The valley remembers your choice.';
assert.equal(M.issues(p).length,0);
process.stdout.write(JSON.stringify(p));
